// Run after changing vehicle-schema.json. Both Android apps use this generated schema.
const fs = require('fs');
const schema = require('./vehicle-schema.json');
const target = require('path').join(__dirname, '../packages/publication_protocol/lib/vehicle_schema.dart');
const generated = `// Generated by functions/generate-schema.js. Do not edit the constants.\nconst requiredVehicleFields = <String>${JSON.stringify(schema.required)};\nconst vehicleFieldLabels = <String, String>${JSON.stringify(schema.labels)};\nconst vehicleEnums = <String, List<String>>${JSON.stringify(schema.enums)};\n`;
const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
fs.writeFileSync(target, generated + existing.slice(existing.indexOf('// Validation implementation.')));
